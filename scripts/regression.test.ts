/**
 * ユーザー辞書（user-lex.csv）の誤読回帰テスト。**行を足す PR の時点で**、実物のシステム辞書に
 * 重ねて解析し直し、直したい読みになるか・既存の複合語を壊さないかを見る。
 *
 * もとは HENGE の `apps/reading/src/user-lex.test.ts` にあった。HENGE 側に置くと、検査が
 * Release の差し替え・本番の再読みより後になり、辞書の更新のたびに HENGE の無関係な PR が落ちる。
 *
 * 誤読を直す行を足したら、その文を「直る」に、壊しそうな複合語を「壊れない」に足す。
 * 実行: `bun scripts/fetch-dict.ts && bun test`（システム辞書が無いと失敗する）
 */
import { describe, expect, test } from "bun:test";
import { readFileSync } from "node:fs";
import { Analyzer, CSV_PATH } from "./lib/reading";

const userCsv = readFileSync(CSV_PATH, "utf8");

function kanaOf(analyzer: Analyzer, text: string): string {
  const result = analyzer.reading(text);
  if ("error" in result) throw new Error(`UNKNOWN_READING: ${result.surface} (${text})`);
  return result.kana;
}

describe("user-lex.csv の書式", () => {
  // 壊れた行が Release に出ると、読み Worker が起動のたびに落ちる
  test("全行が MeCab 書式の13列（表層,lid,rid,cost,特徴9列）", () => {
    const lines = userCsv.split("\n").filter((line) => line !== "" && !line.startsWith("#"));
    expect(lines.length).toBeGreaterThan(0);
    for (const line of lines) {
      const fields = line.split(",");
      expect(fields.length).toBe(13);
      expect(fields[0]).not.toBe("");
      expect(fields[1]).toMatch(/^\d+$/);
      expect(fields[2]).toMatch(/^\d+$/);
      expect(fields[3]).toMatch(/^-?\d+$/);
      expect(fields[11]).not.toBe("");
    }
  });
});

